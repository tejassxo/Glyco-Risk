"""
Integration and schema contract tests for real-time clinical inference and SHAP records.
"""

from pathlib import Path
import json
import pytest
import numpy as np

from src.glycorisk.config import ARTIFACTS_DIR, MODELS_DIR
from src.glycorisk.data.preprocessor import ClinicalPreprocessor
from src.glycorisk.explainability.clinical_forensics import generate_clinical_forensics_record


def test_clinical_forensics_schema_contract():
    """Verify that the Clinical Forensics Record adheres to the exact mandated schema."""
    sample_file = ARTIFACTS_DIR / "sample_clinical_forensics_record.json"
    if not sample_file.exists():
        pytest.skip("sample_clinical_forensics_record.json not yet generated by pipeline.")

    with open(sample_file, "r") as f:
        record = json.load(f)

    required_keys = [
        "patient_id",
        "prediction",
        "risk_probability",
        "confidence_status",
        "top_contributing_factors",
        "model_version",
        "inference_latency_ms",
    ]

    for key in required_keys:
        assert key in record, f"Mandatory key '{key}' missing from Clinical Forensics Record"

    assert isinstance(record["risk_probability"], (float, int))
    assert 0.0 <= record["risk_probability"] <= 1.0
    assert record["confidence_status"] in ["HIGH_CONFIDENCE", "MODERATE_CONFIDENCE", "BORDERLINE_UNCERTAINTY"]
    assert isinstance(record["top_contributing_factors"], list)
    assert record["inference_latency_ms"] < 250.0, f"Inference latency too slow: {record['inference_latency_ms']} ms"
